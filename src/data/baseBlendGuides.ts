import type { BrainwaveChannel } from "@/types/brainwave";

/**
 * ベースブレンド図鑑の解説データ。
 *
 * `public` … 顧客・未ログインにも表示してよい内容
 * `instructor` … 認定インストラクターにのみ表示する内容（使い分け指針・注意事項）
 *
 * 内部配合比率はここには置かない（`src/server/baseBlendPrivateRecipes.ts` を参照）。
 *
 * 表現方針: 本製品は芳香用の雑貨として提供するため、治療・治癒を断定する表現は使わない。
 * 「〜の場面で選ばれます」「〜と言われています」の範囲にとどめること。
 */

export type PairingOil = {
  name: string;
  reason: string;
};

/** 一般公開してよい解説。 */
export type BaseBlendPublicGuide = {
  /** 香りの第一印象を1文で。 */
  scentImpression: string;
  /** 香りの立ち方（トップ→ラスト）の説明。 */
  scentJourney: string;
  recommendedFor: string[];
  scenes: string[];
  timeOfDay: string;
  /** 脳波測定の傾向とブレンド選択のつながり。顧客にも見せる粒度で書く。 */
  brainwaveContext: string;
};

/** 認定インストラクター以上に表示する内容。 */
export type BaseBlendInstructorGuide = {
  /** 似たブレンドとの使い分け。カウンセリング時の判断材料。 */
  selectionGuide: string;
  /** 追加精油の相性と、なぜ合うのか。 */
  pairingOils: PairingOil[];
  /** 足しすぎ・組み合わせ注意。 */
  cautions: string[];
  /** 事前確認が必要な体調・状況。 */
  contraindications: string[];
  /** 測定値のどの傾向に対して提案しやすいか。 */
  brainwaveIndication: {
    channels: BrainwaveChannel[];
    note: string;
  };
};

export type BaseBlendGuide = {
  public: BaseBlendPublicGuide;
  instructor: BaseBlendInstructorGuide;
};

